use oblig_4;

DROP TABLE IF EXISTS AnotherTable;

CREATE TABLE IF NOT EXISTS AnotherTable (
	id INT PRIMARY KEY,
	name TEXT NOT NULL
) WITH SYSTEM VERSIONING;

SET @@timestamp = UNIX_TIMESTAMP('2016-01-01');

INSERT INTO AnotherTable VALUES
	(1, 'Bob'),
	(2, 'Matthew')
;

SET @@timestamp = UNIX_TIMESTAMP('2017-01-01');

INSERT INTO AnotherTable VALUES
	(3, 'Alice')
;

SET @@timestamp = UNIX_TIMESTAMP('2018-01-01');

UPDATE AnotherTable SET name = 'John' WHERE id = 1;

SET @@timestamp = UNIX_TIMESTAMP('2019-01-01');

UPDATE AnotherTable SET name = 'Wendy' WHERE id = 2;

SET @@timestamp = UNIX_TIMESTAMP('2020-01-01');

DELETE FROM AnotherTable WHERE id = 1;

-- WE CHECK THE HISTORY ONE YEAR AT A TIME

SELECT id, name, ROW_START, ROW_END FROM AnotherTable FOR SYSTEM_TIME FROM '2016-01-01 00:00:00' TO '2016-12-01 00:00:00';

SELECT id, name, ROW_START, ROW_END FROM AnotherTable FOR SYSTEM_TIME FROM '2017-01-01 00:00:00' TO '2017-12-01 00:00:00';

SELECT id, name, ROW_START, ROW_END FROM AnotherTable FOR SYSTEM_TIME FROM '2018-01-01 00:00:00' TO '2018-12-01 00:00:00';

SELECT id, name, ROW_START, ROW_END FROM AnotherTable FOR SYSTEM_TIME FROM '2019-01-01 00:00:00' TO '2019-12-01 00:00:00';

SELECT id, name, ROW_START, ROW_END FROM AnotherTable FOR SYSTEM_TIME FROM '2020-01-01 00:00:00' TO '2020-12-01 00:00:00';

-- WE CHECK THE ENTIRE HISTORY
SELECT id, name, ROW_START, ROW_END FROM AnotherTable FOR SYSTEM_TIME FROM '2016-01-01 00:00:00' TO '2026-01-01 00:00:00';

